"""## The model — DenseNet-121 pre-trained on ImageNet

- **Normalisation inside the model.** DenseNet's ImageNet weights expect its own pre-processing.
  We reproduce that with two plain, fully-serialisable Keras layers — `Rescaling(1/255)` then a
  `Normalization` with fixed ImageNet mean/variance.
- **Augmentation as train-only layers** (flip / small rotation / small zoom), identical to the baseline.
- **A small new head:** global average pooling → dropout → a 38-way softmax. The backbone provides the features; only the head is new.

We first build the model with the **backbone frozen** (`trainable=False`) for the head warm-up phase.

Transfer learning reuses features learned on 1.4M ImageNet images, which is exactly the
head-start a 38-class leaf-disease problem with rare classes needs.
"""

# DenseNet-121 transfer model: train-only augmentation + ImageNet normalisation + frozen backbone + small head
data_augment = models.Sequential([
    layers.RandomFlip("horizontal", seed=SEED),
    layers.RandomRotation(0.05, seed=SEED),
    layers.RandomZoom(0.05, seed=SEED),
], name="augment")   # train-only, as in the baseline

DN_MEAN = [0.485, 0.456, 0.406]
DN_STD  = [0.229, 0.224, 0.225]

base_model = DenseNet121(
    include_top=False,
    weights="imagenet",
    input_shape=(IMG_SIZE, IMG_SIZE, 3),
    pooling=None
    )
base_model.trainable = False     # phase 1: freeze backbone, only head learns

def build_densenet():
    inputs = layers.Input((IMG_SIZE, IMG_SIZE, 3))
    x = data_augment(inputs)                            # train-only augmentation
    x = layers.Rescaling(1.0 / 255)(x)
    x = layers.Normalization(axis=-1, mean=DN_MEAN,
                             variance=[s ** 2 for s in DN_STD])(x)
    x = base_model(x, training=False)              # BN stays in inference mode
    x = layers.GlobalAveragePooling2D()(x)
    x = layers.Dropout(0.3)(x)
    outputs = layers.Dense(n_classes, activation="softmax")(x)

    m = models.Model(inputs, outputs, name="densenet121_transfer")

    m.compile(optimizer=tf.keras.optimizers.Adam(HEAD_LR),
              loss="sparse_categorical_crossentropy", metrics=["accuracy"])
    return m

model = build_densenet()

print(f"backbone layers: {len(base_model.layers)} | trainable now: {base_model.trainable}")

model.summary()

"""## Phase 1 — train the head with the backbone frozen

With the backbone frozen, only the new head learns, at the higher learning rate, which is faster.

Fine-tuning a backbone against a *random* head would send large, noisy gradients into the pre-trained weights. Instead the model will first be prepared with a frozen backbone and later receive a fine-tuning in phase 2 (standard two-stage transfer-learning recipe).

"""

