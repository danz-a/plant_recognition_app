"""## Phase 2 — fine-tune the backbone at a low learning rate

Unfreeze the DenseNet backbone and continue training at a lower learning rate, so the
pre-trained features adapt gently to leaf textures instead of being overwritten. We keep the BatchNormalization layers frozen (a standard fine-tuning safeguard): their ImageNet running statistics
are reliable. Early stopping on `val_loss`
restores the best epoch.

Letting the deeper convolutional filters specialise to the disease textures is where transfer learning earns most of its gain over a frozen backbone.
"""

# Phase 2: unfreeze the backbone (keep BatchNorm frozen), recompile at a low LR, fine-tune.
