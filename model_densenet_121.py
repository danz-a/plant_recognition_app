"""## Evaluation (applied to every available model)

> Blockzitat einfügen



`evaluate_model()` bundles all evaluation steps in one place so the exact same analysis runs on each
model:

1. **learning curves** — only when a training `history` is passed (a loaded model has none);
2. **prediction** pass over the validation set;
3. headline **macro-F1** and **accuracy**;
4. **per-class recall** (worst-first, where the imbalance bites);
5. full **classification report**;
6. row-normalised **confusion matrix**.

The driver cell then calls it on the freshly trained model and — if the load cell above was
uncommented — on the loaded model as well.

"""

# One reusable evaluation routine -> identical steps for every model.
def evaluate_model(model, title, history=None, phase_boundary=None):
    """Run every evaluation step on `model` against the validation set (val_ds / yi_val).

    history / phase_boundary are OPTIONAL: pass them for a freshly trained model to also draw the
    learning curves; omit them (e.g. for a loaded model) and that step is skipped.
    Returns (metrics_dict, per_class_dataframe).
    """
    print("=" * 72)
    print(f"Evaluation: {title}")
    print("=" * 72)

    # 1) learning curves - only when a training history is available
    if history is not None:
        fig, ax = plt.subplots(1, 2, figsize=(12, 4))
        ax[0].plot(history["accuracy"], label="train"); ax[0].plot(history["val_accuracy"], label="val")
        ax[1].plot(history["loss"], label="train");     ax[1].plot(history["val_loss"], label="val")
        if phase_boundary is not None:
            for a in ax:
                a.axvline(phase_boundary - 0.5, ls="--", c="grey", lw=1)
        ax[0].set_title("Accuracy"); ax[0].set_xlabel("epoch"); ax[0].legend()
        ax[1].set_title("Loss");     ax[1].set_xlabel("epoch"); ax[1].legend()
        plt.suptitle(f"{title} - learning curves (dashed = fine-tuning starts)")
        plt.tight_layout(); plt.show()
    else:
        print("(no training history -> skipping learning curves)\n")

    # 2) predict the validation set once
    y_true = yi_val
    y_prob = model.predict(val_ds, verbose=0)
    y_pred = y_prob.argmax(axis=1)

    # 3) headline metrics (macro-F1 is the one that matters under 36:1 imbalance)
    mf1 = f1_score(y_true, y_pred, average="macro", zero_division=0)
    acc = accuracy_score(y_true, y_pred)

    print(f"{title}:  macro-F1 = {mf1:.3f}   accuracy = {acc:.3f}\n")

    # 4) per-class recall, sorted worst-first
    rec = recall_score(y_true, y_pred, average=None, labels=range(n_classes), zero_division=0)
    per_class = (pd.DataFrame({
        "class": class_names,
        "recall": rec,
        "val_images": np.bincount(y_true, minlength=n_classes
                                  )})
                 .sort_values("recall"))

    print("Five hardest classes (lowest recall):")
    print(per_class.head().to_string(index=False))
    print("\nFive easiest classes (highest recall):")
    print(per_class.tail().to_string(index=False))

    # 5) full per-class breakdown
    print("\n" + classification_report(
        y_true, y_pred,
        target_names=class_names,
        digits=3,
        zero_division=0
        ))

    # 6) row-normalised confusion matrix (diagonal = per-class recall)
    cm = confusion_matrix(y_true, y_pred, labels=range(n_classes)).astype(float)
    cm_norm = np.divide(cm, cm.sum(axis=1, keepdims=True),
                        out=np.zeros_like(cm), where=cm.sum(axis=1, keepdims=True) > 0)
    plt.figure(figsize=(10, 8))
    sns.heatmap(cm_norm, cmap="viridis", vmin=0, vmax=1, square=True,
                xticklabels=class_names, yticklabels=class_names,
                cbar_kws={"shrink": 0.7, "label": "fraction of true class"})
    plt.xticks(rotation=90, fontsize=7); plt.yticks(rotation=0, fontsize=7)
    plt.xlabel("predicted"); plt.ylabel("true (diagonal = recall)")
    plt.title(f"{title} - row-normalised confusion matrix (validation set)")
    plt.tight_layout(); plt.show()

    return {"macro_F1": mf1, "accuracy": acc}, per_class

